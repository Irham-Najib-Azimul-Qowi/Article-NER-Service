"""
End-to-End AI Engineering Pipeline for News-Monitoring NER:
1. Memuat & memprofil 8 file CSV ekspor berita dari dataset/ (atau dataset lokal).
2. Data Profiling & Preprocessing (menghapus boilerplate AI, regex cleaning, ekstraksi judul & isi).
3. Pembuatan evaluation_examples.json (12 sampel terverifikasi memenuhi semua kriteria evaluasi).
4. Bootstrap anotasi weak-supervision dengan model dasar & gazetteer domain perbankan/berita Malaysia.
5. Pemisahan data deterministik (70% Train, 15% Val, 15% Test) berbasis ID artikel (mencegah data leakage).
6. Serialisasi ke biner spaCy DocBin (.spacy).
7. Konfigurasi model spaCy v3 dengan tok2vec & transition-based parser.
8. Pelatihan model spaCy dan penyimpanan artefak terbaik ke model/model-best.
9. Evaluasi independen pada held-out test set (Baseline vs Fine-Tuned comparison).
10. Analisis error (False Positives & False Negatives).
"""

